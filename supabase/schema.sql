-- Smart Canteen database schema
-- Run in Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  class_name text not null default '',
  role text not null default 'student' check (role in ('student', 'staff', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name_ru text not null,
  name_uz text not null,
  sort_order int not null default 0
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name_ru text not null,
  name_uz text not null,
  description_ru text not null default '',
  description_uz text not null default '',
  category_id bigint references public.categories(id) on delete set null,
  category text not null default 'Основные блюда',
  price integer not null check (price >= 0),
  half_price integer check (half_price is null or half_price >= 0),
  image_url text not null default '',
  available boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.products add column if not exists half_price integer check (half_price is null or half_price >= 0);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  order_number bigint generated by default as identity unique,
  student_name text not null,
  class_name text not null default '',
  pickup_slot text not null,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'preparing', 'ready', 'collected', 'cancelled')),
  total integer not null check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price integer not null check (unit_price >= 0)
);

create table if not exists public.queue_slots (
  id bigint generated by default as identity primary key,
  slot_time text not null unique,
  capacity integer not null default 15 check (capacity > 0),
  enabled boolean not null default true
);

-- Migration for an existing Smart Canteen database.
alter table public.orders add column if not exists student_name text;
alter table public.orders add column if not exists class_name text not null default '';
update public.orders o
set student_name = coalesce(nullif(p.full_name, ''), 'Ученик')
from public.profiles p
where p.id = o.user_id and o.student_name is null;
alter table public.orders alter column student_name set default 'Ученик';
alter table public.orders alter column student_name set not null;

-- New auth users get a student profile automatically.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, class_name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'class_name', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.queue_slots enable row level security;

-- Helper: staff and admins may manage cafeteria operations.
create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('staff', 'admin')
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create policy "profiles read own or staff"
on public.profiles for select
using (id = auth.uid() or public.is_staff());

create policy "profiles update own"
on public.profiles for update
using (id = auth.uid())
with check (id = auth.uid() and role = 'student');

create policy "categories public read"
on public.categories for select using (true);
create policy "categories admin manage"
on public.categories for all using (public.is_admin()) with check (public.is_admin());

create policy "products public read"
on public.products for select using (true);
create policy "products admin manage"
on public.products for all using (public.is_admin()) with check (public.is_admin());

create policy "orders read own or staff"
on public.orders for select
using (user_id = auth.uid() or public.is_staff());

create policy "orders student create own"
on public.orders for insert
with check (user_id = auth.uid());

create policy "orders staff update"
on public.orders for update
using (public.is_staff())
with check (public.is_staff());

create policy "order items read own or staff"
on public.order_items for select
using (
  exists (
    select 1 from public.orders o
    where o.id = order_id and (o.user_id = auth.uid() or public.is_staff())
  )
);

create policy "order items insert own order"
on public.order_items for insert
with check (
  exists (
    select 1 from public.orders o
    where o.id = order_id and o.user_id = auth.uid()
  )
);

create policy "queue slots public read"
on public.queue_slots for select using (true);
create policy "queue slots admin manage"
on public.queue_slots for all using (public.is_admin()) with check (public.is_admin());

